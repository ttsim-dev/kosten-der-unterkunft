def _built_output_names() -> frozenset[str]:
    """Every file under `bld/tables` and `bld/figures` a manifest row could name."""
    directories = (TABLES, BLD / "figures")
    return frozenset(
        path.name
        for directory in directories
        if directory.is_dir()
        for path in directory.iterdir()
        if path.is_file()
    )


def _built_output_count() -> int:
    """Count the files under `bld/tables` and `bld/figures` a manifest row could name."""
