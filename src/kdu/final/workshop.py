def workshop_deck(
    figures: tuple[MainFigure, ...] = MAIN_FIGURES,
) -> tuple[MainFigure, ...]:
    """Return the figures admitted to the main talk (§19).

    Args:
        figures: The §19 main-figure programme.

    Returns:
        The selected figures in §19 order.

    Raises:
        ValueError: If more than `MAX_WORKSHOP_FIGURES` are selected, or if a
            selected figure is not built.

    """
    selected = tuple(figure for figure in figures if figure.in_deck)
    if len(selected) > MAX_WORKSHOP_FIGURES:
        msg = (
            f"§19 admits at most {MAX_WORKSHOP_FIGURES} figures to the main "
            f"talk; {len(selected)} are selected"
        )
        raise ValueError(msg)
    pending = [
        figure.filename
        for figure in selected
        if figure.status is not FigureStatus.BUILT
    ]
    if pending:
        msg = f"a figure in the deck is not built yet: {', '.join(pending)}"
        raise ValueError(msg)
    return selected


