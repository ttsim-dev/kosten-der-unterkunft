def _sign_shares(frame: pd.DataFrame, household_size: int) -> dict[str, float]:
    cell = frame.loc[
        (frame["benchmark_variant"] == str(PRIMARY_BENCHMARK))
        & (frame["household_size"] == household_size)
        & frame["proxy_error_eur"].notna()
    ]
    error = cell["proxy_error_eur"].astype(float)
    return {
        "negative": 100.0 * float((error < 0).mean()),
        "positive": 100.0 * float((error > 0).mean()),
        "zero": 100.0 * float((error == 0).mean()),
    }


def _weighted_tier_share(coverage: pd.DataFrame, column: str) -> float:
    weights = coverage["n_gemeinden_main_sample"].astype(float)
    return float((coverage[column].astype(float) * weights).sum() / weights.sum())
